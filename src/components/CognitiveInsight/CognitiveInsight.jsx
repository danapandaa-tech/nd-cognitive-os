import { useState } from 'react';
import { useStore } from '../../logic/useStore';
import { buildInsightContext, generateInsight } from '../../logic/insightEngine';

export default function CognitiveInsight() {
  const cognitiveState = useStore((s) => s.cognitiveState);
  const profile = useStore((s) => s.profile);
  const getPatterns = useStore((s) => s.getPatterns);

  const [insight, setInsight] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);

  const handleGenerate = async () => {
    setLoading(true);
    setError(null);
    try {
      const patterns = getPatterns();
      const context = buildInsightContext(cognitiveState, patterns, profile);
      const text = await generateInsight(context);
      setInsight(text);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-lg font-medium text-gray-100 mb-1">Cognitive Insight</h2>
        <p className="text-sm text-indigo-300/70">
          AI-powered interpretation of your patterns (NVIDIA Nemotron via Nebius)
        </p>
      </div>

      {/* State Context */}
      <section className="card">
        <h3 className="label mb-3">Current Context</h3>
        <div className="grid grid-cols-3 gap-3 text-center">
          <div>
            <p className="text-xs text-gray-500">State</p>
            <p className="text-sm text-gray-200 capitalize mt-1">{cognitiveState.current}</p>
          </div>
          <div>
            <p className="text-xs text-gray-500">Energy</p>
            <p className="text-sm text-gray-200 capitalize mt-1">{cognitiveState.energy}</p>
          </div>
          <div>
            <p className="text-xs text-gray-500">Sensory</p>
            <p className="text-sm text-gray-200 capitalize mt-1">{cognitiveState.sensory}</p>
          </div>
        </div>
      </section>

      {/* Generate Button */}
      <button
        onClick={handleGenerate}
        disabled={loading}
        className="w-full py-3 px-4 rounded-lg font-medium text-sm transition-colors
          bg-indigo-600 hover:bg-indigo-500 disabled:bg-indigo-900/50 disabled:text-gray-500 text-white"
      >
        {loading ? (
          <span className="flex items-center justify-center gap-2">
            <span className="animate-spin">◌</span> Nemotron is thinking...
          </span>
        ) : (
          'Generate Insight'
        )}
      </button>

      {/* Error */}
      {error && (
        <section className="card border-red-500/30 bg-red-500/5">
          <p className="text-sm text-red-300">{error}</p>
        </section>
      )}

      {/* Insight Result */}
      {insight && !loading && (
        <section className="card border-emerald-500/20 bg-emerald-500/5">
          <h3 className="label mb-3 text-emerald-300">Your Insight</h3>
          <div className="prose prose-sm prose-invert max-w-none">
            {insight.split('\n').map((line, i) => (
              line.trim() ? <p key={i} className="text-sm text-gray-200 leading-relaxed mb-2">{line}</p> : null
            ))}
          </div>
          <p className="text-xs text-gray-500 mt-3 pt-2 border-t border-gray-800">
            Generated by NVIDIA Nemotron-3.5-Lightning via Nebius Token Factory. Your data stays local — only anonymised state summary was sent.
          </p>
        </section>
      )}

      {/* Privacy Note */}
      {!insight && !loading && (
        <p className="text-xs text-gray-600 text-center">
          Click above to get a personalized interpretation powered by NVIDIA Nemotron. No personal data is sent — only your state, energy, and pattern types.
        </p>
      )}
    </div>
  );
}
